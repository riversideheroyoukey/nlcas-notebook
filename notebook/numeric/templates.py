"""Deterministic code templates for NumericTask (N-1 phase 1).

Template-driven generation from the structured spec — the same principle as
backend command building (CLAUDE.md core principle #3: commands are generated
deterministically from specs; the LLM may ADVISE on the spec but is not the
final authority over the generated code).  Phase 1 covers parameter_sweep and
plotting (implementation memo §11); both evaluate the forked theory
expression over one swept variable, save a figure (+ a CSV table for sweeps),
and print a machine-readable summary line for the reflux step.
"""
from __future__ import annotations

import math

from notebook.models.numeric import NumericTask, PHASE1_PROBLEM_TYPES
from notebook.numeric.expr_to_numpy import canonical_to_numpy
from notebook.runtime.backend_handler import canonical_name_to_latex
from notebook.runtime.shared_parser import UnknownNotationError

# The generated code prints one line `NB_RESULT {json}` — the runner parses
# it into the result artifact.
RESULT_MARKER = "NB_RESULT"

# Typed manifest line (docs/26 §4): declares the produced artifacts (name /
# value_kind / value_type / value-or-file) plus node diagnostics.  Emitted IN
# ADDITION to NB_RESULT — the runner reads both, so old code artifacts keep
# working and old runners simply ignore the new line.
MANIFEST_MARKER = "NB_MANIFEST"

# Full-width numeric characters → half-width.  The numeric modal's fixed-value
# inputs POST straight to /numeric/fork as JSON, bypassing the NL pipeline's
# _fullwidth_to_halfwidth, so a Japanese IME's full-width digits reach the
# template unnormalized — and the project accepts full-width digits by policy
# (CLAUDE.md H-5z).
_FW_TO_HW = str.maketrans("０１２３４５６７８９．＋－Ｅｅ", "0123456789.+-Ee")


def _py_number(value: str) -> str:
    """Validate a fixed/sweep value as a plain FINITE number and return its
    NORMALIZED half-width form (adversarial-input rule: fixed_values go into
    generated code verbatim, so they must BE a valid Python numeric literal).

    ``float()`` alone is too permissive here: it parses full-width digits
    (``float('０.３') == 0.3``) and inf/nan — but ``'０.３'`` is a SyntaxError
    as Python source and ``inf``/``nan`` are names, not literals.  So normalize
    full-width → half-width first, then reject anything non-finite, and return
    the normalized (compilable) string rather than the raw input.
    """
    normalized = str(value).translate(_FW_TO_HW).strip()
    try:
        num = float(normalized)
    except (TypeError, ValueError):
        raise UnknownNotationError("numeric.bad_value", value=str(value))
    if not math.isfinite(num):
        raise UnknownNotationError("numeric.bad_value", value=str(value))
    return normalized


def _mathtext(name: str, context) -> str:
    """Wrap *name* for matplotlib's built-in mathtext parser (no LaTeX install
    needed) IF it actually has a LaTeX form (Greek letter, subscript, a
    registered latex_name) — plain names pass through unwrapped so a bare
    'a' or 'k' doesn't grow spurious italics."""
    tex = canonical_name_to_latex(name, context)
    return f"${tex}$" if tex != name else name


def _single_line(text: str) -> str:
    """Collapse a canonical into one physical line, safe to embed in a
    single-line ``#`` comment.  Maxima pretty-prints long expressions across
    multiple lines (continuation-indented); embedded verbatim, the
    continuation lines lose the leading ``#`` and become a Python
    IndentationError."""
    return " ".join(text.split())


def _provenance_header(task: NumericTask) -> str:
    """The generated script's leading docstring: full fork provenance, shared
    by every template."""
    return f'''"""Auto-generated by the notebook numeric layer (N-1).

task_id   : {task.task_id}
source    : {", ".join(task.source_expression_ids)}  ({_single_line(task.source_canonical)})
branch    : {task.source_branch_id}
assumptions: {", ".join(task.source_assumption_ids) or "-"}
approximations: {", ".join(task.approximations) or "-"}
Edit freely — this is a reviewable PoC scaffold, not a black box.
"""'''


def generate_code(task: NumericTask, context=None, lang='en') -> "tuple[str, dict]":
    """Render *task* into runnable Python source.

    Returns (source, meta) where meta records the numpy expression and the
    resolved binding of every free symbol (provenance for the code artifact).
    Raises UnknownNotationError with an i18n key on any spec problem —
    unsupported type, unsupported notation, unbound symbols, bad values.
    """
    from notebook.numeric.plot_spec import is_cartesian
    if is_cartesian(task.spec) or (task.spec and task.spec.intent.kind == "cartesian_plot"):
        from notebook.numeric.plot_codegen import generate_plot_code
        return generate_plot_code(task, context, lang)
    if task.problem_type not in PHASE1_PROBLEM_TYPES:
        raise UnknownNotationError("numeric.unsupported_problem_type",
                                   problem_type=task.problem_type)
    if task.problem_type == "function_evaluation":
        return _generate_evaluate(task, context)
    if task.problem_type == "minimize_1d":
        return _generate_minimize(task, context)
    if task.problem_type == "self_consistent_loop":
        return _generate_loop(task, context)
    if task.problem_type == "eigenvalue_problem":
        return _generate_eigen(task, context)
    if len(task.sweep_parameters) != 1:
        raise UnknownNotationError("numeric.need_one_sweep",
                                   count=len(task.sweep_parameters))

    expr_np, free = canonical_to_numpy(task.source_canonical, context)

    sweep_var, sweep = next(iter(task.sweep_parameters.items()))
    lo = _py_number(str(sweep.get("min", 0)))
    hi = _py_number(str(sweep.get("max", 1)))
    points = int(sweep.get("points", 200))

    unbound = sorted(free - {sweep_var} - set(task.fixed_values))
    if unbound:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(unbound))

    fixed_lines = "\n".join(
        f"{name} = {_py_number(val)}"
        for name, val in sorted(task.fixed_values.items())
        if name in free
    )

    target = task.target_quantity or "y"
    want_table = task.problem_type == "parameter_sweep"

    # Figure caption: which symbols were held fixed, and at what value — a
    # plot with no context is unreadable once two or three runs pile up in
    # the timeline with different parameters.  Greek/subscripted names are
    # rendered via matplotlib's mathtext (same GREEK_CMD table the rest of
    # the UI uses), not left as bare canonical identifiers.
    target_label = _mathtext(target, context)
    sweep_label = _mathtext(sweep_var, context)
    fixed_label = ", ".join(
        f"{_mathtext(name, context)}={val}"
        for name, val in sorted(task.fixed_values.items())
        if name in free)
    fig_title = f"{target_label}({sweep_label})"
    if fixed_label:
        fig_title += f"   |   {fixed_label}"

    src = f'''{_provenance_header(task)}
import json
import os

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- sweep ---
{sweep_var} = np.linspace({lo}, {hi}, {points})

# --- theory expression: {_single_line(task.source_canonical)} ---
{target} = {expr_np}
{target} = np.broadcast_to({target}, {sweep_var}.shape).astype(float)

fig, ax = plt.subplots(figsize=(6, 4))
ax.plot({sweep_var}, {target})
ax.set_xlabel({sweep_label!r})
ax.set_ylabel({target_label!r})
ax.set_title({fig_title!r})
ax.grid(True, alpha=0.3)
fig.tight_layout()
fig.savefig(os.path.join(OUT, "figure.png"), dpi=110)
'''
    if want_table:
        src += f'''
np.savetxt(os.path.join(OUT, "table.csv"),
           np.column_stack([{sweep_var}, {target}]),
           delimiter=",", header="{sweep_var},{target}", comments="")
'''
    manifest_artifacts = (
        f'[{{"name": {target!r}, "value_kind": "series", '
        f'"value_type": "real_float64", "over": [{sweep_var!r}], '
        f'"file": "table.csv"}}]'
    ) if want_table else "[]"
    src += f'''
_i_min = int(np.argmin({target}))
_i_max = int(np.argmax({target}))
print("{RESULT_MARKER}", json.dumps({{
    "target": {target!r},
    "sweep_var": {sweep_var!r},
    "n_points": {points},
    "min": {{"x": float({sweep_var}[_i_min]), "y": float({target}[_i_min])}},
    "max": {{"x": float({sweep_var}[_i_max]), "y": float({target}[_i_max])}},
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": {manifest_artifacts},
    "diagnostics": {{"success": True, "method": "direct_eval"}},
}}))
'''
    meta = {
        "numpy_expr": expr_np,
        "sweep_var": sweep_var,
        "sweep": {"min": lo, "max": hi, "points": points},
        "fixed_values": {k: v for k, v in task.fixed_values.items() if k in free},
    }
    return src, meta


def _generate_evaluate(task: NumericTask, context=None) -> "tuple[str, dict]":
    """function_evaluation (docs/26 §10): evaluate the expression at one fully
    fixed point and emit a typed scalar via the manifest — the chaining
    workhorse (its value binds into a downstream task's fixed input).

    No sweep, no figure.  A complex result is reported honestly as
    complex_float64 with {re, im} (the whitelist maps %i → 1j, so e.g.
    exp(%i*x) evaluates complex) — the binding compatibility table then
    refuses to feed it into a real-only fixed input.
    """
    if task.sweep_parameters:
        raise UnknownNotationError("numeric.evaluate_no_sweep",
                                   count=len(task.sweep_parameters))

    from notebook.numeric.expr_to_numpy import is_matrix_canonical
    if is_matrix_canonical(task.source_canonical):
        return _generate_matrix_evaluate(task, context)

    expr_np, free = canonical_to_numpy(task.source_canonical, context)

    unbound = sorted(free - set(task.fixed_values))
    if unbound:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(unbound))

    fixed_lines = "\n".join(
        f"{name} = {_py_number(val)}"
        for name, val in sorted(task.fixed_values.items())
        if name in free
    )
    target = task.target_quantity or "y"

    src = f'''{_provenance_header(task)}
import json
import os

import numpy as np

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- theory expression: {_single_line(task.source_canonical)} ---
_val = np.asarray({expr_np}, dtype=complex).item()
_is_real = abs(_val.imag) <= 1e-12 * max(1.0, abs(_val.real))

if _is_real:
    _value = float(_val.real)
    _entry = {{"name": {target!r}, "value_kind": "scalar",
              "value_type": "real_float64", "value": _value}}
else:
    _value = {{"re": float(_val.real), "im": float(_val.imag)}}
    _entry = {{"name": {target!r}, "value_kind": "scalar",
              "value_type": "complex_float64", "value": _value}}

print("{RESULT_MARKER}", json.dumps({{"target": {target!r}, "value": _value}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [_entry],
    "diagnostics": {{"success": True, "method": "direct_eval"}},
}}))
'''
    meta = {
        "numpy_expr": expr_np,
        "fixed_values": {k: v for k, v in task.fixed_values.items() if k in free},
    }
    return src, meta


def _generate_eigen(task: NumericTask, context=None) -> "tuple[str, dict]":
    """eigenvalue_problem (docs/26 §10, G3): evaluate the matrix canonical
    and diagonalize, fused into one script (same philosophy as the loop —
    never one process per grid point).

    Two modes, keyed by the sweep count:
      0 sweeps — eigenvalues (typed vector, ascending / eigenvalue_order)
        + eigenvectors (typed matrix, columns matching that order) at one
        fully fixed point.
      1 sweep — eigenvalue BRANCHES over the grid: figure + branches.csv
        (the S-y avoided-crossing use case).  Eigenvectors are not emitted
        in sweep mode.

    Hermiticity is checked numerically (at every grid point in sweep mode):
    Hermitian → np.linalg.eigh (real, ascending — the physics default);
    non-Hermitian → np.linalg.eig, sorted by real part, and diagnostics
    carry non_hermitian=True so the researcher SEES the regime change.
    """
    from notebook.numeric.expr_to_numpy import (
        canonical_matrix_to_numpy, is_matrix_canonical,
    )

    if not is_matrix_canonical(task.source_canonical):
        raise UnknownNotationError("numeric.eigen_needs_matrix")
    if len(task.sweep_parameters) > 1:
        raise UnknownNotationError("numeric.need_one_sweep",
                                   count=len(task.sweep_parameters))

    rows, free, (m, n) = canonical_matrix_to_numpy(task.source_canonical,
                                                   context)
    if m != n:
        raise UnknownNotationError("numeric.eigen_needs_square", m=m, n=n)

    sweep_var = next(iter(task.sweep_parameters), None)
    unbound = sorted(free - ({sweep_var} if sweep_var else set())
                     - set(task.fixed_values))
    if unbound:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(unbound))

    fixed_lines = "\n".join(
        f"{name} = {_py_number(val)}"
        for name, val in sorted(task.fixed_values.items())
        if name in free
    )
    target = task.target_quantity or "E"
    matrix_src = ",\n         ".join(
        "[" + ", ".join(cells) + "]" for cells in rows)

    header = _provenance_header(task)
    common_top = f'''{header}
import json
import os

import numpy as np
'''

    if sweep_var is None:
        # --- point mode: eigenvalues + eigenvectors ---
        src = f'''{common_top}
OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- theory matrix: {_single_line(task.source_canonical)} ---
_M = np.array([
         {matrix_src},
], dtype=complex)

_hermitian = bool(np.allclose(_M, _M.conj().T, atol=1e-12))
if _hermitian:
    _vals, _vecs = np.linalg.eigh(_M)          # real, ascending
    _vals = _vals.astype(float)
else:
    _vals, _vecs = np.linalg.eig(_M)
    _order = np.argsort(_vals.real)
    _vals, _vecs = _vals[_order], _vecs[:, _order]

_has_nan = bool(np.isnan(_vals.real).any())

def _num(x):
    if abs(complex(x).imag) <= 1e-12 * max(1.0, abs(complex(x).real)):
        return float(complex(x).real)
    return {{"re": float(complex(x).real), "im": float(complex(x).imag)}}

_val_list = [_num(v) for v in _vals]
_vec_list = [[_num(x) for x in row] for row in _vecs]
_vtype = ("real_float64" if all(isinstance(v, float) for v in _val_list)
          else "complex_float64")

print("{RESULT_MARKER}", json.dumps({{
    "target": {target!r},
    "eigenvalues": _val_list,
    "hermitian": _hermitian,
    "has_nan": _has_nan,
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [
        {{"name": "eigenvalues", "value_kind": "vector", "value_type": _vtype,
         "shape": [{m}], "value": _val_list,
         "ordering": {{"kind": "sorted_by_value", "ascending": True}}}},
        {{"name": "eigenvectors", "value_kind": "matrix", "value_type": _vtype,
         "shape": [{m}, {m}], "value": _vec_list,
         "ordering": {{"kind": "eigenvalue_order"}}}},
    ],
    "diagnostics": {{"success": not _has_nan, "method": "numpy_eig",
                    "hermitian": _hermitian,
                    "non_hermitian": not _hermitian}},
}}))
'''
        meta = {
            "matrix_shape": [m, n], "mode": "point",
            "fixed_values": {k: v for k, v in task.fixed_values.items()
                             if k in free},
        }
        return src, meta

    # --- sweep mode: eigenvalue branches over the grid ---
    sweep = task.sweep_parameters[sweep_var]
    lo = _py_number(str(sweep.get("min", 0)))
    hi = _py_number(str(sweep.get("max", 1)))
    points = int(sweep.get("points", 200))
    sweep_label = _mathtext(sweep_var, context)
    fixed_label = ", ".join(
        f"{_mathtext(name, context)}={val}"
        for name, val in sorted(task.fixed_values.items()) if name in free)
    fig_title = f"eigenvalue branches({sweep_label})"
    if fixed_label:
        fig_title += f"   |   {fixed_label}"

    src = f'''{common_top}import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

_grid = np.linspace({lo}, {hi}, {points})
_branches = np.empty(({points}, {m}))
_all_hermitian = True
for _i, {sweep_var} in enumerate(_grid):
    # --- theory matrix: {_single_line(task.source_canonical)} ---
    _M = np.array([
         {matrix_src},
    ], dtype=complex)
    if np.allclose(_M, _M.conj().T, atol=1e-12):
        _branches[_i] = np.linalg.eigvalsh(_M)      # real, ascending
    else:
        _all_hermitian = False
        _branches[_i] = np.sort(np.linalg.eigvals(_M).real)

_has_nan = bool(np.isnan(_branches).any())

fig, ax = plt.subplots(figsize=(6, 4))
for _b in range({m}):
    ax.plot(_grid, _branches[:, _b])
ax.set_xlabel({sweep_label!r})
ax.set_ylabel({target!r})
ax.set_title({fig_title!r})
ax.grid(True, alpha=0.3)
fig.tight_layout()
fig.savefig(os.path.join(OUT, "figure.png"), dpi=110)

np.savetxt(os.path.join(OUT, "branches.csv"),
           np.column_stack([_grid, _branches]), delimiter=",",
           header="{sweep_var}," + ",".join(
               f"lambda{{_b + 1}}" for _b in range({m})),
           comments="")

print("{RESULT_MARKER}", json.dumps({{
    "target": {target!r},
    "sweep_var": {sweep_var!r},
    "n_branches": {m},
    "branch_min": float(np.nanmin(_branches)),
    "branch_max": float(np.nanmax(_branches)),
    "hermitian": bool(_all_hermitian),
    "has_nan": _has_nan,
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [{{"name": "branches", "value_kind": "series",
                   "value_type": "real_float64", "over": [{sweep_var!r}],
                   "ordering": {{"kind": "sorted_by_value", "ascending": True}},
                   "file": "branches.csv"}}],
    "diagnostics": {{"success": not _has_nan, "method": "numpy_eig",
                    "hermitian": bool(_all_hermitian),
                    "non_hermitian": not _all_hermitian}},
}}))
'''
    meta = {
        "matrix_shape": [m, n], "mode": "sweep", "sweep_var": sweep_var,
        "sweep": {"min": lo, "max": hi, "points": points},
        "fixed_values": {k: v for k, v in task.fixed_values.items()
                         if k in free},
    }
    return src, meta


def _generate_matrix_evaluate(task: NumericTask, context=None) -> "tuple[str, dict]":
    """Matrix evaluate (docs/26 §10, G2): a Maxima ``matrix(...)`` canonical
    at one fully fixed point → a typed matrix artifact (shape=[m,n]).  Cells
    are lowered individually through the scalar whitelist (surface-level
    decomposition — see canonical_matrix_to_numpy); a complex matrix is
    reported honestly as complex_float64 with {re, im} per cell.
    """
    from notebook.numeric.expr_to_numpy import canonical_matrix_to_numpy

    rows, free, (m, n) = canonical_matrix_to_numpy(task.source_canonical,
                                                   context)
    unbound = sorted(free - set(task.fixed_values))
    if unbound:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(unbound))
    fixed_lines = "\n".join(
        f"{name} = {_py_number(val)}"
        for name, val in sorted(task.fixed_values.items())
        if name in free
    )
    target = task.target_quantity or "M"
    matrix_src = ",\n    ".join(
        "[" + ", ".join(cells) + "]" for cells in rows)

    src = f'''{_provenance_header(task)}
import json
import os

import numpy as np

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- theory matrix: {_single_line(task.source_canonical)} ---
_M = np.array([
    {matrix_src},
], dtype=complex)

_has_nan = bool(np.isnan(_M.real).any() or np.isnan(_M.imag).any())
_is_real = bool(np.allclose(_M.imag, 0.0, atol=1e-12))
if _is_real:
    _value = [[float(x) for x in row] for row in _M.real]
    _vtype = "real_float64"
else:
    _value = [[{{"re": float(x.real), "im": float(x.imag)}} for x in row]
              for row in _M]
    _vtype = "complex_float64"

print("{RESULT_MARKER}", json.dumps({{
    "target": {target!r},
    "matrix_shape": [{m}, {n}],
    "has_nan": _has_nan,
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [{{"name": {target!r}, "value_kind": "matrix",
                   "value_type": _vtype, "shape": [{m}, {n}],
                   "value": _value}}],
    "diagnostics": {{"success": not _has_nan, "method": "direct_eval"}},
}}))
'''
    meta = {
        "matrix_shape": [m, n],
        "cells": rows,
        "fixed_values": {k: v for k, v in task.fixed_values.items() if k in free},
    }
    return src, meta


def _generate_minimize(task: NumericTask, context=None) -> "tuple[str, dict]":
    """minimize_1d (docs/26 §10, G2): bounded 1-D minimization via
    scipy.optimize.minimize_scalar.  The single "sweep" entry carries the
    BOUNDS (min/max — no grid), reusing the flat container so no new task
    field is needed.  Emits two typed scalars — ``<var>_star`` (argmin) and
    ``<target>_min`` (minimum) — plus honest diagnostics: iterations,
    convergence, and whether the solution sits on a bound (a boundary
    solution usually means the physical minimum lies OUTSIDE the searched
    interval — exactly what a researcher must not miss).
    """
    if len(task.sweep_parameters) != 1:
        raise UnknownNotationError("numeric.need_one_bounded",
                                   count=len(task.sweep_parameters))

    expr_np, free = canonical_to_numpy(task.source_canonical, context)

    var, bounds = next(iter(task.sweep_parameters.items()))
    lo = _py_number(str(bounds.get("min", 0)))
    hi = _py_number(str(bounds.get("max", 1)))

    unbound = sorted(free - {var} - set(task.fixed_values))
    if unbound:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(unbound))

    fixed_lines = "\n".join(
        f"{name} = {_py_number(val)}"
        for name, val in sorted(task.fixed_values.items())
        if name in free
    )
    target = task.target_quantity or "y"
    # Stopping tolerance: from the faceted spec's method params when given.
    tol = 1e-8
    if task.spec is not None and task.spec.method.params.get("tol") is not None:
        tol = float(_py_number(str(task.spec.method.params["tol"])))

    argmin_name = f"{var}_star"
    min_name = f"{target}_min"

    src = f'''{_provenance_header(task)}
import json
import os

import numpy as np
from scipy.optimize import minimize_scalar

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- objective: {_single_line(task.source_canonical)} ---
def _objective({var}):
    return float({expr_np})

_res = minimize_scalar(_objective, bounds=({lo}, {hi}), method="bounded",
                       options={{"xatol": {tol}}})
_argmin = float(_res.x)
_minimum = float(_res.fun)
_span = {hi} - {lo}
_boundary = min(_argmin - {lo}, {hi} - _argmin) <= max({tol}, 1e-6 * _span)

print("{RESULT_MARKER}", json.dumps({{
    "target": {target!r},
    "variable": {var!r},
    "argmin": _argmin,
    "minimum": _minimum,
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [
        {{"name": {argmin_name!r}, "value_kind": "scalar",
         "value_type": "real_float64", "value": _argmin}},
        {{"name": {min_name!r}, "value_kind": "scalar",
         "value_type": "real_float64", "value": _minimum}},
    ],
    "diagnostics": {{"success": bool(_res.success), "method": "brent_bounded",
                    "iterations": int(getattr(_res, "nit", -1)),
                    "function_evaluations": int(getattr(_res, "nfev", -1)),
                    "boundary_solution": bool(_boundary),
                    "message": str(getattr(_res, "message", ""))}},
}}))
'''
    meta = {
        "numpy_expr": expr_np,
        "variable": var,
        "bounds": {"min": lo, "max": hi},
        "tol": tol,
        "fixed_values": {k: v for k, v in task.fixed_values.items() if k in free},
    }
    return src, meta


def _generate_loop(task: NumericTask, context=None) -> "tuple[str, dict]":
    """self_consistent_loop (docs/26 §8): the multi-expression body is FUSED
    into one script — the iteration runs in-process, and only the converged
    state + trace come back.  Node-per-iteration execution would pay the
    sandbox startup (~0.7 s) every pass; fusion is the enabling design, not
    an optimization.

    Structure of the generated loop:
      1. evaluate the body assignments in order (each a whitelist-lowered
         theory expression),
      2. apply the update map (state_var ← body_output),
      3. residual = max |Δstate|; record the trace row; stop when < tol.

    Non-convergence is an HONEST outcome: diagnostics.success=False and the
    engine records a failed step (same philosophy as the NaN net — never a
    clean success wrapping a garbage number).
    """
    spec = task.spec
    body = task.source_body or []
    if spec is None or not body:
        raise UnknownNotationError("numeric.spec.loop_no_body")
    params = spec.method.params or {}
    update = {str(k): str(v) for k, v in (params.get("update") or {}).items()}
    if not update:
        raise UnknownNotationError("numeric.spec.loop_no_update")

    states = list(update.keys())
    body_names = [str(b.get("name", "")) for b in body]
    for var, src_name in update.items():
        if src_name not in body_names:
            raise UnknownNotationError("numeric.spec.loop_bad_update",
                                       var=var, source=src_name)

    tol = float(_py_number(str(params.get("tol", 1e-8))))
    max_iter = int(float(_py_number(str(params.get("max_iter", 1000)))))

    # Initial values: every state variable needs a free input with an initial.
    initials: dict[str, str] = {}
    for v in spec.inputs:
        if v.role == "free" and (v.spec or {}).get("initial") is not None:
            initials[v.name] = _py_number(str(v.spec["initial"]))
    missing_init = sorted(set(states) - set(initials))
    if missing_init:
        raise UnknownNotationError("numeric.missing_values",
                                   symbols=", ".join(missing_init))

    # Lower each body assignment in order; a symbol must be bound by the
    # fixed values, the state variables, or an EARLIER body output.
    fixed = dict(task.fixed_values)
    lowered: list[tuple[str, str]] = []
    seen: set = set()
    used_fixed: set = set()
    for b in body:
        name = str(b.get("name", ""))
        expr_np, free = canonical_to_numpy(str(b.get("canonical", "")), context)
        unbound = sorted(free - set(fixed) - set(states) - seen)
        if unbound:
            raise UnknownNotationError("numeric.missing_values",
                                       symbols=", ".join(unbound))
        used_fixed |= free & set(fixed)
        lowered.append((name, expr_np))
        seen.add(name)

    fixed_lines = "\n".join(f"{n} = {_py_number(fixed[n])}"
                            for n in sorted(used_fixed))
    init_lines = "\n".join(f"{s} = {initials[s]}" for s in states)
    body_lines = "\n    ".join(f"{n} = float({e})" for n, e in lowered)
    new_lines = "\n    ".join(f"_new_{s} = float({update[s]})" for s in states)
    _diffs = [f"abs(_new_{s} - {s})" for s in states]
    resid_expr = _diffs[0] if len(_diffs) == 1 else "max(" + ", ".join(_diffs) + ")"
    assign_lines = "\n    ".join(f"{s} = _new_{s}" for s in states)
    trace_header = "iteration," + ",".join(states) + ",residual"
    trace_row = "(_it, " + ", ".join(states) + ", _resid)"
    state_json = "{" + ", ".join(f"{s!r}: float({s})" for s in states) + "}"
    manifest_scalars = ", ".join(
        f'{{"name": {s!r}, "value_kind": "scalar", '
        f'"value_type": "real_float64", "value": float({s})}}'
        for s in states)

    src = f'''{_provenance_header(task)}
import json
import os

import numpy as np

OUT = os.environ.get("NB_NUMERIC_OUT", ".")

# --- fixed parameters (from NumericTask.fixed_values) ---
{fixed_lines or "# (none)"}

# --- state initialization (free inputs) ---
{init_lines}

_tol = {tol}
_max_iter = {max_iter}
_trace = []
_converged = False
_resid = float("inf")
_it = 0

for _it in range(1, _max_iter + 1):
    # --- loop body (theory expressions, evaluated in order) ---
    {body_lines}
    # --- update map ---
    {new_lines}
    _resid = {resid_expr}
    {assign_lines}
    _trace.append({trace_row})
    if _resid < _tol:
        _converged = True
        break

np.savetxt(os.path.join(OUT, "trace.csv"), np.array(_trace),
           delimiter=",", header="{trace_header}", comments="")

_state = {state_json}
print("{RESULT_MARKER}", json.dumps({{
    "target": {",".join(states)!r},
    "state": _state,
    "iterations": _it,
    "converged": _converged,
    "residual": _resid,
}}))
print("{MANIFEST_MARKER}", json.dumps({{
    "artifacts": [{manifest_scalars},
        {{"name": "trace", "value_kind": "trace",
         "value_type": "real_float64", "over": ["iteration"],
         "ordering": {{"kind": "indexed_by_parameter"}},
         "file": "trace.csv"}}],
    "diagnostics": {{"success": _converged, "method": "fixed_point",
                    "iterations": _it, "converged": _converged,
                    "final_residual": _resid}},
}}))
'''
    meta = {
        "body": [{"name": n, "numpy_expr": e} for n, e in lowered],
        "update": update,
        "tol": tol,
        "max_iter": max_iter,
        "initials": initials,
        "fixed_values": {k: v for k, v in fixed.items() if k in used_fixed},
    }
    return src, meta
